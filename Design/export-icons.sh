#!/bin/zsh
# Exports every app icon from the SVG masters in Design/ (macOS only: uses QuickLook + sips).
#   iOS:     AppIcon-Pagecrane.svg → AppIcon.appiconset (all sizes, opaque)
#   Android: android/*.svg → adaptive layers + legacy launcher icons
#   In-app:  256 px PNG → app/assets/brand/icon.png (Home header)
#   Launch:  rounded 96 pt icon → iOS LaunchImage + Android drawable-*/splash_icon.png
# Run from anywhere:  zsh Design/export-icons.sh
set -euo pipefail
DESIGN="${0:A:h}"
APP="$DESIGN/../app"
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

render() { # svg → $TMP/<name>.svg.png at 1024 px (QuickLook paints onto white)
  qlmanage -t -s 1024 -o "$TMP" "$1" >/dev/null 2>&1
  echo "$TMP/${1:t}.png"
}

render_transparent() { # svg → RGBA png: render over black and over white, then solve for alpha
  local name=${1:t:r}
  sed 's|\(<svg [^>]*>\)|\1<rect width="1024" height="1024" fill="#000"/>|' "$1" > "$TMP/$name-on-black.svg"
  sed 's|\(<svg [^>]*>\)|\1<rect width="1024" height="1024" fill="#fff"/>|' "$1" > "$TMP/$name-on-white.svg"
  local b=$(render "$TMP/$name-on-black.svg") w=$(render "$TMP/$name-on-white.svg")
  python3 -I "$DESIGN/tools/matte.py" "$b" "$w" "$TMP/$name-rgba.png"
  echo "$TMP/$name-rgba.png"
}

# --- master, flattened to opaque (App Store rejects icons with alpha) ---
m=$(render "$DESIGN/AppIcon-Pagecrane.svg")
sips -s format jpeg -s formatOptions 100 "$m" --out "$TMP/m.jpg" >/dev/null
sips -s format png "$TMP/m.jpg" --out "$DESIGN/AppIcon-Pagecrane-1024.png" >/dev/null
MASTER="$DESIGN/AppIcon-Pagecrane-1024.png"

# --- iOS ---
SET="$APP/ios/Runner/Assets.xcassets/AppIcon.appiconset"
for spec in 20x1 20x2 20x3 29x1 29x2 29x3 40x1 40x2 40x3 60x2 60x3 76x1 76x2 83.5x2 1024x1; do
  s=${spec%x*}; k=${spec#*x}
  px=$(python3 -c "print(round($s*$k))")
  sips -z $px $px "$MASTER" --out "$SET/Icon-App-${s}x${s}@${k}x.png" >/dev/null
done

# --- Android: legacy square icons + adaptive layers (108 dp canvas) ---
RES="$APP/android/app/src/main/res"
fg=$(render_transparent "$DESIGN/android/AppIcon-Pagecrane-foreground.svg")
bg=$(render "$DESIGN/android/AppIcon-Pagecrane-background.svg")
mono=$(render_transparent "$DESIGN/android/AppIcon-Pagecrane-monochrome.svg")
for pair in mdpi:1 hdpi:1.5 xhdpi:2 xxhdpi:3 xxxhdpi:4; do
  d=${pair%:*}; k=${pair#*:}
  legacy=$(python3 -c "print(round(48*$k))"); layer=$(python3 -c "print(round(108*$k))")
  mkdir -p "$RES/mipmap-$d"
  sips -z $legacy $legacy "$MASTER" --out "$RES/mipmap-$d/ic_launcher.png" >/dev/null
  sips -z $layer $layer "$fg"   --out "$RES/mipmap-$d/ic_launcher_foreground.png" >/dev/null
  sips -z $layer $layer "$bg"   --out "$RES/mipmap-$d/ic_launcher_background.png" >/dev/null
  sips -z $layer $layer "$mono" --out "$RES/mipmap-$d/ic_launcher_monochrome.png" >/dev/null
done
mkdir -p "$RES/mipmap-anydpi-v26"
cat > "$RES/mipmap-anydpi-v26/ic_launcher.xml" <<'XML'
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by Design/export-icons.sh: edit the SVG masters, not this file. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@mipmap/ic_launcher_background" />
    <foreground android:drawable="@mipmap/ic_launcher_foreground" />
    <monochrome android:drawable="@mipmap/ic_launcher_monochrome" />
</adaptive-icon>
XML

# --- in-app brand asset ---
mkdir -p "$APP/assets/brand"
sips -z 256 256 "$MASTER" --out "$APP/assets/brand/icon.png" >/dev/null

# --- launch screens: 96 pt / 96 dp rounded icon, centred on the app background ---
# (Android 12+ draws its own splash from the launcher icon; this one is for Android 5–11.)
sips -z 384 384 "$MASTER" --out "$TMP/splash-384.png" >/dev/null
python3 -I "$DESIGN/tools/round.py" "$TMP/splash-384.png" "$TMP/splash.png"
LAUNCH="$APP/ios/Runner/Assets.xcassets/LaunchImage.imageset"
sips -z 96 96   "$TMP/splash.png" --out "$LAUNCH/LaunchImage.png" >/dev/null
sips -z 192 192 "$TMP/splash.png" --out "$LAUNCH/LaunchImage@2x.png" >/dev/null
sips -z 288 288 "$TMP/splash.png" --out "$LAUNCH/LaunchImage@3x.png" >/dev/null
for pair in mdpi:1 hdpi:1.5 xhdpi:2 xxhdpi:3 xxxhdpi:4; do
  d=${pair%:*}; k=${pair#*:}
  px=$(python3 -c "print(round(96*$k))")
  mkdir -p "$RES/drawable-$d"
  sips -z $px $px "$TMP/splash.png" --out "$RES/drawable-$d/splash_icon.png" >/dev/null
done

echo "Exported iOS, Android, in-app and launch-screen icons from AppIcon-Pagecrane.svg"
